#!/usr/bin/env python3
"""Fail-closed comparison: published archive bytes and article character streams must match.
The result must NEVER be called '1:1 complete' if a page or file failed retrieval.
"""
import argparse,hashlib,json,re,sys
from pathlib import Path
from bs4 import BeautifulSoup
import yaml
ROOT=Path(__file__).resolve().parents[1]

def exact_text(doc):
    soup=BeautifulSoup(str(doc),'html.parser')
    for node in soup.find_all(['script','style','template']): node.decompose()
    return ''.join(soup.strings)

def validate(require_import=False):
    errors=[];warnings=[];counts={}
    for key,collection,count in [('books','_ksiazki',41),('brochures','_broszury',39)]:
        files=list((ROOT/collection).glob('*.md'));counts[key]=len(files)
        if len(files)!=count: errors.append('Zła liczba '+collection)
        snap=json.loads((ROOT/'_data/catalog_web_snapshot.json').read_text())
        ref={x['number']:x for x in snap[key]}
        for p in files:
            try:
                raw=p.read_text(encoding='utf-8'); data=yaml.safe_load(raw.split('---',2)[1]); n=data['catalog_number']
                if not require_import and not data.get('source_text_verified'):
                    for field,original in (('title','title'),('author','author'),('catalog_status','status')):
                        if data.get(field)!=ref[n].get(original):errors.append(f'{p}: {field} różni się od odczytu katalogu')
                if require_import and not data.get('source_text_verified'):errors.append(f'{p}: katalog niezweryfikowany z HTML')
                if data.get('description') or raw.split('---',2)[2].strip():errors.append(f'{p}: nieudokumentowany opis')
                if data.get('source_provenance') not in ('original-downloaded-html','web-catalog-snapshot-2026-11-17'):errors.append(f'{p}: pochodzenie niejasne')
            except Exception as exc:errors.append(f'{p}: {exc}')
    for p in (ROOT/'_artykuly').glob('*.md'):
        try:
            data=yaml.safe_load(p.read_text(encoding='utf-8').split('---',2)[1]);raw=p.read_text(encoding='utf-8')
            if not data.get('imported_from_legacy') or not data.get('source_verified'):errors.append(f'{p}: artykuł bez dowodu źródła')
            if '{% raw %}' not in raw or '{% endraw %}' not in raw:errors.append(f'{p}: niekompletny surowy HTML')
            content=raw.split('{% raw %}\n',1)[1].rsplit('\n{% endraw %}',1)[0]
            text=exact_text(BeautifulSoup(content,'html.parser'))
            if hashlib.sha256(text.encode('utf-8')).hexdigest()!=data['source_text_sha256']:errors.append(f'{p}: zmiana znaków po imporcie')
            if len(text)!=data['source_char_count']:errors.append(f'{p}: liczba znaków różni się')
            # Independently reopen exact original raw bytes, not only metadata
            # generated by the importer, to expose any omitted source text.
            import urllib.parse
            origin=urllib.parse.urlsplit(data['source_url'])
            alias='wswch' if origin.hostname and 'wswch.pl' in origin.hostname else 'swch'
            local_path=urllib.parse.unquote(origin.path).lstrip('/') or 'index.html'
            archive=ROOT/'_source_archive'/alias/local_path
            if not archive.is_file(): errors.append(f'{p}: brak surowego pliku źródła')
            else:
                # Matching encoding follows the actual source import method.
                from bs4 import UnicodeDammit
                original=UnicodeDammit(archive.read_bytes(),is_html=True).unicode_markup or archive.read_bytes().decode('windows-1250',errors='replace')
                soup=BeautifulSoup(original,'html.parser')
                expected=exact_text(soup.body or soup)
                if hashlib.sha256(expected.encode('utf-8')).hexdigest()!=data['source_text_sha256']:
                    errors.append(f'{p}: SHA-256 nie zgadza się z niezależnie otwartym źródłem')
        except Exception as exc:errors.append(f'{p}: {exc}')
    manifest=ROOT/'migration-report.json'
    if require_import:
        if not manifest.exists(): errors.append('Brak migration-report.json; publikacja zablokowana')
        else:
            report=json.loads(manifest.read_text(encoding='utf-8'))
            if report.get('status')!='VERIFIED':errors.append('Stan migracji nie jest VERIFIED')
            if report['summary'].get('errors'):errors.append('Błędy importu w raporcie')
            if report['summary'].get('books_verified')!=41 or report['summary'].get('brochures_verified')!=39: errors.append('Niezweryfikowany katalog')
            for obj in report.get('archived_html_pages',[]):
                url=obj['url'];relative=obj['path'].lstrip('/');public=ROOT/relative
                if not public.is_file():errors.append('Brak kopii HTML '+url);continue
                if hashlib.sha256(public.read_bytes()).hexdigest()!=obj['sha256']:errors.append('Niezgodne bajty kopii HTML '+url)
            if len(report.get('archived_html_pages',[]))!=report['summary'].get('source_html_pages',-1):errors.append('Liczba stron HTML niezgodna')
            if len(report.get('articles',[]))!=len(list((ROOT/'_artykuly').glob('*.md'))):errors.append('Liczba artykułów niezgodna')
            # No claim of complete website inventory without known external sitemap.
            warnings.append('Brak dowodu kompletności adresów niepodlinkowanych i treści generowanych dynamicznie.')
    else: warnings.append('Brak pełnego pobranego źródła; snapshot katalogu nie jest dowodem 1:1 całych stron')
    result={'pass':not errors,'errors':errors,'warnings':warnings,'counts':counts}
    (ROOT/'STRICT_AUDIT.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(result,ensure_ascii=False,indent=2));return not errors

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--require-import',action='store_true');options=parser.parse_args()
    sys.exit(0 if validate(require_import=options.require_import) else 1)
